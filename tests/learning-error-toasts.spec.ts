import { expect, test } from '@playwright/test';

test('learning loading failure shows toast inside modal and allows retry', async ({ page }) => {
  await page.goto('/');
  await page.getByRole('button', { name: 'Add phrase' }).first().click();
  const dialog = page.getByRole('dialog');
  await dialog.getByLabel('Original phrase').fill('Learning load');
  await dialog.getByLabel('Translation').fill('Translation');
  await dialog.getByRole('button', { name: 'Save phrase' }).click();
  await expect(dialog).toBeHidden();
  await page.getByRole('button', { name: 'Start learning' }).click();
  await page.route('**/', route => route.request().method() === 'POST' ? route.abort() : route.continue());
  await dialog.getByRole('button', { name: 'Start session' }).click();
  await expect(dialog.getByRole('listitem').filter({ hasText: 'Could not load entries.' })).toBeVisible();
  await expect(dialog.getByRole('alert')).toContainText('Check the database and try again.');
  await page.unrouteAll();
  await dialog.getByRole('button', { name: 'Start session' }).click();
  await expect(page.getByLabel('Answer')).toBeVisible();
});

test('evaluation failure shows actionable toast and retains answer guidance', async ({ page }) => {
  await page.goto('/');
  await page.getByRole('button', { name: 'Add phrase' }).first().click();
  const dialog = page.getByRole('dialog');
  await dialog.getByLabel('Original phrase').fill('Learning answer');
  await dialog.getByLabel('Translation').fill('Translation');
  await dialog.getByRole('button', { name: 'Save phrase' }).click();
  await expect(dialog).toBeHidden();
  await page.getByRole('button', { name: 'Start learning' }).click();
  await dialog.getByRole('button', { name: 'Start session' }).click();
  await page.getByLabel('Answer').fill('Different answer');
  await page.route('**/', route => route.request().method() === 'POST' ? route.abort() : route.continue());
  await page.getByRole('button', { name: 'Submit answer' }).click();
  await expect(page.getByRole('listitem').filter({ hasText: 'Could not evaluate your answer.' })).toContainText('provider charge');
  await expect(page.getByLabel('Answer')).toHaveValue('Different answer');
  await expect(page.locator('#answer-error')).toContainText('provider charge');
});

test('learning answer validation appears on submit and revalidates on correction', async ({ page }) => {
  await page.goto('/');
  await page.getByRole('button', { name: 'Add phrase' }).first().click();
  const dialog = page.getByRole('dialog');
  await dialog.getByLabel('Original phrase').fill('Learning answer');
  await dialog.getByLabel('Translation').fill('Translation');
  await dialog.getByRole('button', { name: 'Save phrase' }).click();
  await expect(dialog).toBeHidden();
  await page.getByRole('button', { name: 'Start learning' }).click();
  await dialog.getByRole('button', { name: 'Start session' }).click();
  const answer = page.getByLabel('Answer');
  const error = page.locator('#answer-error');
  await answer.fill('   ');
  await expect(error).toHaveCount(0);
  const normalBorder = await answer.evaluate(el => getComputedStyle(el).borderColor);
  await page.getByRole('button', { name: 'Submit answer' }).click();
  await expect(error).toHaveText('Enter a value.');
  await expect(error).toHaveAttribute('role', 'alert');
  await expect(answer).toHaveAttribute('aria-invalid', 'true');
  await expect(answer).toHaveAttribute('aria-describedby', 'answer-error');
  await expect(page.getByRole('listitem').filter({ hasText: 'Check your answer and try again.' })).toHaveCount(0);
  await expect(error).toHaveCSS('color', 'rgb(220, 38, 38)');
  await expect(answer).toHaveCSS('border-top-color', 'rgb(220, 38, 38)');
  expect(normalBorder).not.toBe('rgb(220, 38, 38)');
  expect(parseFloat(await answer.evaluate(el => getComputedStyle(el).borderTopWidth))).toBeGreaterThan(0);
  await answer.fill('Valid');
  await expect(error).toHaveCount(0);
  await expect(answer).toHaveAttribute('aria-invalid', 'false');
  await answer.fill(' '.repeat(3));
  await expect(error).toHaveText('Enter a value.');
  await answer.fill('x'.repeat(2001));
  await expect(error).toHaveText('Use at most 2,000 Unicode code points.');
  await answer.fill('Valid');
  await expect(error).toHaveCount(0);
});
