import { expect, test } from './isolation/fixture';

test('add and edit confirmations are brief and old timers cannot clear a newer confirmation', async ({ page }, testInfo) => {
  await page.clock.install();
  await page.goto('/');
  await page.clock.pauseAt(await page.evaluate(() => Date.now() + 1000));
  const phrase = `Confirmation timing ${testInfo.project.name}`;
  await page.getByRole('button', { name: 'Add phrase' }).first().click();
  const dialog = page.getByRole('dialog');
  await dialog.getByLabel('Original phrase').fill(phrase);
  await dialog.getByLabel('Translation').fill('Translation');
  await dialog.getByRole('button', { name: 'Save phrase' }).click();
  await expect(dialog).toBeHidden();
  await page.clock.runFor(100);
  const notifications = page.getByRole('region', { name: /Notifications/ });
  await expect(notifications).toHaveAttribute('aria-live', 'polite');
  const added = notifications.getByRole('listitem').filter({ hasText: 'Phrase added.' });
  const updated = notifications.getByRole('listitem').filter({ hasText: 'Phrase updated.' });
  await expect(added).toBeVisible();
  await expect(added).toHaveAttribute('data-type', 'success');
  await expect(added.getByRole('button', { name: /close/i })).toHaveCount(0);
  await page.clock.fastForward(4000);
  await expect(added).toBeVisible();

  await page.getByRole('article').filter({ hasText: phrase }).getByRole('button', { name: 'Edit phrase' }).click();
  await dialog.getByLabel('Translation').fill('Updated translation');
  await dialog.getByRole('button', { name: 'Save phrase' }).click();
  await expect(dialog).toBeHidden();
  await page.clock.runFor(100);
  await expect(updated).toBeVisible();
  await page.clock.fastForward(1500);
  await expect(updated).toBeVisible();
  await page.clock.fastForward(4000);
  await page.clock.runFor(500);
  await expect(updated).toBeHidden();

  await page.getByRole('button', { name: 'Add phrase' }).first().click();
  await dialog.getByLabel('Original phrase').fill(`${phrase} second`);
  await dialog.getByLabel('Translation').fill('Translation');
  await dialog.getByRole('button', { name: 'Save phrase' }).click();
  await expect(dialog).toBeHidden();
  await page.clock.runFor(100);
  await expect(added).toBeVisible();
  await page.clock.fastForward(5500);
  await page.clock.runFor(500);
  await expect(added).toBeHidden();
});

test('deletion confirmation is announced and disappears after five seconds', async ({ page }, testInfo) => {
  await page.clock.install();
  await page.goto('/');
  await page.clock.pauseAt(await page.evaluate(() => Date.now() + 1000));
  const phrase = `Deletion timing ${testInfo.project.name}`;
  await page.getByRole('button', { name: 'Add phrase' }).first().click();
  const dialog = page.getByRole('dialog');
  await dialog.getByLabel('Original phrase').fill(phrase);
  await dialog.getByLabel('Translation').fill('Translation');
  await dialog.getByRole('button', { name: 'Save phrase' }).click();
  await expect(dialog).toBeHidden();
  await page.clock.runFor(100);
  await page.getByRole('article').filter({ hasText: phrase }).getByRole('button', { name: 'Delete phrase' }).click();
  await dialog.getByRole('button', { name: 'Delete', exact: true }).click();
  await expect(dialog).toBeHidden();
  await page.clock.runFor(100);
  const notifications = page.getByRole('region', { name: /Notifications/ });
  await expect(notifications).toHaveAttribute('aria-live', 'polite');
  const confirmation = notifications.getByRole('listitem').filter({ hasText: 'Phrase deleted.' });
  await expect(confirmation).toBeVisible();
  await page.clock.fastForward(4000);
  await expect(confirmation).toBeVisible();
  await page.clock.fastForward(1500);
  await page.clock.runFor(500);
  await expect(confirmation).toBeHidden();
});
